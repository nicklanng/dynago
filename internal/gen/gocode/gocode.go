// clone emits a deep copy, used as the independent snapshot a loaded entity remembers.
func (g *gen) clone(e *schema.Entity) {
	g.p("// clone copies e, including its slices and maps, without its loaded state.")
	g.p("func (e *%s) clone() %s {", e.GoName, e.GoName)
	g.p("c := *e")
	g.p("c.loaded = nil")
	for _, f := range e.Fields {
		switch f.Type {
		case schema.TypeBytes:
			g.p("c.%s = append([]byte(nil), e.%s...)", f.GoName, f.GoName)
		case schema.TypeList, schema.TypeStringSet:
			g.p("c.%s = append([]string(nil), e.%s...)", f.GoName, f.GoName)
		case schema.TypeMap:
			g.p("if e.%s != nil {", f.GoName)
			g.p("c.%s = make(map[string]string, len(e.%s))", f.GoName, f.GoName)
			g.p("for k, v := range e.%s {", f.GoName)
			g.p("c.%s[k] = v", f.GoName)
			g.p("}")
			g.p("}")
		}
	}
	g.p("return c")
	g.p("}")
	g.p("")
}

// separators maps each string or enum field to the characters that follow it in the keys that
// identify items: an entity's own key, copies, claims, counters, and GSI partition keys (which
// decide whose query an entry appears in). If a value contained the character after it, "a#b" +
// "c" and "a" + "b#c" would render the same key. A field at the end of a template needs no check:
// once every earlier field is free of its separator, the rest of the key can only belong to the
// last field. GSI sort keys are not checked either: entries there need not be unique, so a name
// like "Drill #2" only affects where it sorts.
//
// Fields linked by a `requires` key (Loan.toolId keys the Tool, so it holds Tool.toolId values)
// carry one value between entities, so they share their separators: a tool id that could never
// appear in a loan's keys is rejected when the tool is created, not when someone borrows it.
func (g *gen) separators() map[*schema.Field]string {
	if g.seps != nil {
		return g.seps
	}
	own := map[*schema.Field]string{}
	add := func(e *schema.Entity, t schema.Template) {
		segs := t.Segments
		for i, sg := range segs {
			if !sg.IsField() || i+1 == len(segs) {
				continue
			}
			f := e.Field(sg.Field)
			if f == nil || (f.Type != schema.TypeString && f.Type != schema.TypeEnum && f.Type != schema.TypeStringSet) {
				continue
			}
			own[f] += string([]rune(segs[i+1].Literal)[0])
		}
	}
	// Group fields linked by requires keys (union-find).
	parent := map[*schema.Field]*schema.Field{}
	var find func(f *schema.Field) *schema.Field
	find = func(f *schema.Field) *schema.Field {
		if p, ok := parent[f]; ok && p != f {
			root := find(p)
			parent[f] = root
			return root
		}
		return f
	}
	for _, e := range g.m.Entities {
		add(e, e.PK)
		add(e, e.SK)
		for _, ix := range e.Indexes {
			add(e, ix.PK)
			if ix.HasSK && ix.Strategy == schema.StrategyCopy {
				add(e, ix.SK)
			}
		}
		for _, u := range e.Uniques {
			add(e, u.PK)
			add(e, u.SK)
		}
		for _, c := range e.Counters {
			add(e, c.PK)
			add(e, c.SK)
		}
		for _, w := range e.Writes {
			for _, rq := range w.Requires {
				for _, k := range rq.Key {
					if a, b := find(k.Source), find(k.Target); a != b {
						parent[a] = b
					}
				}
			}
		}
	}
	group := map[*schema.Field]string{}
	for f, seps := range own {
		group[find(f)] += seps
	}
	g.seps = map[*schema.Field]string{}
	for _, e := range g.m.Entities {
		for _, f := range e.Fields {
			if seps := dedupeChars(group[find(f)]); seps != "" {
				g.seps[f] = seps
			}
		}
	}
	return g.seps
}

func dedupeChars(s string) string {
	var b strings.Builder
	for _, r := range s {
		if !strings.ContainsRune(b.String(), r) {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// keyPartChecks emits a CheckKeyPart for each of fields that appears in a key template.
// keyPartCheck emits a CheckKeyPart for one value of f (an element, if f is a set).
func (g *gen) keyPartCheck(f *schema.Field, val, ret string) {
	sep := g.separators()[f]
	if sep == "" {
		return
	}
	if f.Type == schema.TypeEnum {
		val = "string(" + val + ")"
	}
	g.p("if err := dynago.CheckKeyPart(%q, %s, %q); err != nil {", f.Name, val, sep)
	g.p("%s", ret)
	g.p("}")
}

func (g *gen) keyPartChecks(fields []*schema.Field, expr func(*schema.Field) string, ret string) {
	for _, f := range fields {
		if f.Type == schema.TypeStringSet && g.separators()[f] != "" {
			g.p("for _, elem := range %s {", expr(f))
			g.keyPartCheck(f, "elem", ret)
			g.p("}")
			continue
		}
		g.keyPartCheck(f, expr(f), ret)
	}
}

// changedKeyPartChecks emits separator checks for the fields an update changes. Unchanged
// fields keep whatever they held, so an item stored before a key used them stays writable.
func (g *gen) changedKeyPartChecks(w *schema.Write, skip ...*schema.Field) {
	e := w.Entity
	seps := g.separators()
	g.keyPartChecks(w.Args, func(f *schema.Field) string { return "v." + f.GoName }, "return err")
	var sets []*schema.Field
	vals := map[*schema.Field]string{}
	for _, s := range w.Sets {
		sets = append(sets, s.Field)
		vals[s.Field] = literal(e, s.Field, s.Value)
	}
	g.keyPartChecks(sets, func(f *schema.Field) string { return vals[f] }, "return err")
	for _, f := range w.Patch {
		if seps[f] == "" || slices.Contains(skip, f) {
			continue
		}
		g.p("if v.%s != nil {", f.GoName)
		g.keyPartChecks([]*schema.Field{f}, func(f *schema.Field) string { return "*v." + f.GoName }, "return err")
		g.p("}")
	}
}

// checkKeyParts emits a method validating every field of the entity used in a key.
func (g *gen) checkKeyParts(e *schema.Entity) {
	g.p("// checkKeyParts rejects values containing a character their key templates use as a separator.")
	g.p("func (e *%s) checkKeyParts() error {", e.GoName)
	g.keyPartChecks(e.Fields, func(f *schema.Field) string { return "e." + f.GoName }, "return err")
	g.p("return nil")
	g.p("}")
	g.p("")
}

// typeDoc builds a type's doc comment: "X is a ..." when the schema doc is a noun phrase with an
// article, otherwise a generated first sentence followed by the schema doc as its own paragraph.
func typeDoc(name, doc, fallback string) string {
	if doc == "" {
		return name + " " + fallback
	}
	switch strings.ToLower(strings.Fields(doc)[0]) {
	case "a", "an", "the", "one":
		return name + " is " + lowerInitial(doc)
	}
	return name + " " + fallback + "\n\n" + doc
}

func hasVersionedWrites(e *schema.Entity) bool {
	for _, w := range e.Writes {
		if w.Kind != schema.WriteCreate {
			return true
		}
	}
	return false
}

// versionHelpers emits the functions that resolve dynago.From / dynago.IfVersion for a write.
func (g *gen) versionHelpers(e *schema.Entity) {
	lo := lowerFirst(e.GoName)
	fast, slow := false, false
	for _, w := range e.Writes {
		if w.Kind == schema.WriteCreate {
			continue
		}
		if w.ReadFirst {
			slow = true
		}
		if !w.ReadFirst || len(patchFastPath(w)) > 0 {
			fast = true
		}
	}
	g.p("// from returns the entity passed with dynago.From, checked to be this item and read from the")
	g.p("// store, or nil if none was passed.")
	g.p("func (s *%sStore) from(key dynago.Key, o dynago.WriteOptions) (*%s, error) {", e.GoName, e.GoName)
	g.p("if o.From == nil {")
	g.p("return nil, nil")
	g.p("}")
	g.p("from, ok := o.From.(*%s)", e.GoName)
	g.p("if !ok || from == nil || from.loaded == nil {")
	g.p("return nil, fmt.Errorf(\"%%w: dynago.From needs a *%s read from its own item, not built by hand or read through a copy index\", dynago.ErrVersionRequired)", e.GoName)
	g.p("}")
	g.p("if fk, err := from.Key().dynamoKey(); err != nil || fk != key {")
	g.p("return nil, fmt.Errorf(\"%%w: the %s passed with dynago.From is a different item\", dynago.ErrInvalidKey)", e.Name)
	g.p("}")
	g.p("return from, nil")
	g.p("}")
	g.p("")
	if fast {
		ttl := ""
		if e.TTL != nil {
			ttl = fmt.Sprintf(", TTLAttr: %q", g.m.Table.TTLAttr)
		}
		g.p("// guard resolves the conditions a single-request write must meet.")
		g.p("func (s *%sStore) guard(key dynago.Key, o dynago.WriteOptions, required bool) (dynago.Guard, error) {", e.GoName)
		g.p("expect, err := o.ExpectedRev()")
		g.p("if err != nil {")
		g.p("return dynago.Guard{}, err")
		g.p("}")
		g.p("from, err := s.from(key, o)")
		g.p("if err != nil {")
		g.p("return dynago.Guard{}, err")
		g.p("}")
		g.p("if from != nil {")
		g.p("if expect != 0 && expect != from.loaded.rev {")
		g.p("return dynago.Guard{}, dynago.ErrVersionMismatch")
		g.p("}")
		g.p("expect = from.loaded.rev")
		g.p("}")
		g.p("if required && expect == 0 {")
		g.p("return dynago.Guard{}, dynago.ErrVersionRequired")
		g.p("}")
		g.p("return dynago.Guard{ExpectRev: expect, Version: %sVersion%s, NotFound: Err%sNotFound}, nil", lo, ttl, e.GoName)
		g.p("}")
		g.p("")
	}
	if slow {
		g.p("// start returns the state a read-modify-write starts from: the entity passed with dynago.From")
		g.p("// (no read), or a consistent read. versioned reports whether the caller named a version, in")
		g.p("// which case a concurrent change is a mismatch for the caller rather than something to retry.")
		g.p("func (s *%sStore) start(ctx context.Context, key dynago.Key, o dynago.WriteOptions, required bool) (*%sItem, bool, error) {", e.GoName, lo)
		g.p("expect, err := o.ExpectedRev()")
		g.p("if err != nil {")
		g.p("return nil, false, err")
		g.p("}")
		g.p("from, err := s.from(key, o)")
		g.p("if err != nil {")
		g.p("return nil, false, err")
		g.p("}")
		g.p("if from != nil {")
		g.p("if expect != 0 && expect != from.loaded.rev {")
		g.p("return nil, false, dynago.ErrVersionMismatch")
		g.p("}")
		g.p("return &%sItem{%s: from.loaded.snapshot, Rev: from.loaded.rev, V: from.loaded.v}, true, nil", lo, e.GoName)
		g.p("}")
		g.p("if required && expect == 0 {")
		g.p("return nil, false, dynago.ErrVersionRequired")
		g.p("}")
		g.p("it, err := s.load(ctx, key, true)")
		g.p("if err != nil {")
		g.p("return nil, false, err")
		g.p("}")
		g.p("if expect != 0 && it.Rev != expect {")
		g.p("return nil, false, dynago.ErrVersionMismatch")
		g.p("}")
		g.p("return it, expect != 0, nil")
		g.p("}")
		g.p("")
	}
}

// newerGuard refuses to rewrite an item that newer code wrote: this code would drop what the newer
// schema stored and compute its derived items with the older definitions.
func (g *gen) newerGuard(e *schema.Entity) {
	lo := lowerFirst(e.GoName)
	g.p("if it.V > %sVersion {", lo)
	g.p("return fmt.Errorf(\"%%w: %s at v%%d, this code is v%%d\", dynago.ErrNewerSchema, it.V, %sVersion)", e.Name, lo)
	g.p("}")
}

func (g *gen) docComment(name, doc, generated string) {
	if doc == "" {
		comment(&g.buf, name+" "+generated)
		return
	}
	comment(&g.buf, name+" "+generated+"\n\n"+doc)
}

// presenceGuard emits an early return when a sparse field used in a key is empty.
func (g *gen) presenceGuard(fields []*schema.Field, recv, ret string) {
	pc := presence(fields, recv)
	if pc == "" {
		return
	}
	g.p("if %s {", negate(pc))
	g.p("%s", ret)
	g.p("}")
}

func maintains(e *schema.Entity) string {
	var parts []string
	for _, c := range e.Counters {
		parts = append(parts, "counter "+c.Name)
	}
	for _, u := range e.Uniques {
		parts = append(parts, "unique claim "+u.Name)
	}
	for _, ix := range e.Indexes {
		if ix.Strategy == schema.StrategyCopy {
			parts = append(parts, "copy index "+ix.Name)
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return " In the same transaction it maintains " + strings.Join(parts, ", ") + "."
}

// affected names the indexes and derived items an update can change, which is why it reads first.
func affected(w *schema.Write) string {
	e := w.Entity
	changed := map[*schema.Field]bool{}
	for _, f := range w.Changed() {
		changed[f] = true
	}
	touches := func(lists ...[]*schema.Field) bool {
		for _, l := range lists {
			for _, f := range l {
				if changed[f] {
					return true
				}
			}
		}
		return false
	}
	predFields := func(ps []*schema.Pred) []*schema.Field {
		var out []*schema.Field
		for _, p := range ps {
			out = append(out, p.Field)
		}
		return out
	}
	var parts []string
	for _, ix := range e.Indexes {
		in := [][]*schema.Field{ix.PK.Fields, predFields(ix.Where)}
		if ix.HasSK {
			in = append(in, ix.SK.Fields)
		}
		if ix.Strategy == schema.StrategyCopy {
			in = append(in, ix.ProjectedFields())
		}
		if touches(in...) {
			parts = append(parts, fmt.Sprintf("the %s index entry", ix.Name))
		}
	}
	for _, c := range e.Counters {
		in := [][]*schema.Field{c.KeyFields()}
		for _, v := range c.Values {
			in = append(in, predFields(v.Where))
			if v.Sum != nil {
				in = append(in, []*schema.Field{v.Sum})
			}
		}
		if touches(in...) {
			parts = append(parts, "counter "+c.Name)
		}
	}
	for _, u := range e.Uniques {
		if touches(u.Fields) {
			parts = append(parts, "unique claim "+u.Name)
		}
	}
	return strings.Join(parts, ", ")
}

func hasLimitArgs(e *schema.Entity) bool {
	for _, c := range e.Counters {
		for _, v := range c.Values {
			if v.LimitArg {
				return true
			}
		}
	}
	return false
}

func readCost(c *schema.Counter, consistent bool) string {
	if c.Shards > 1 {
		return fmt.Sprintf("one %s BatchGetItem over %d shards", consistency(consistent), c.Shards)
	}
	return fmt.Sprintf("one %s GetItem", consistency(consistent))
}

func consistency(consistent bool) string {
	if consistent {
		return "strongly consistent"
	}
	return "eventually consistent"
}

func counterValueText(v *schema.CounterValue) string {
	var b strings.Builder
	if v.Sum != nil {
		fmt.Fprintf(&b, "is the sum of %s", v.Sum.Name)
	} else {
		b.WriteString("counts items")
	}
	if len(v.Where) > 0 {
		fmt.Fprintf(&b, " where %s", predText(v.Where))
	}
	switch {
	case v.LimitArg:
		b.WriteString("; writes that grow it take a caller-supplied limit")
	case v.Limit > 0:
		fmt.Fprintf(&b, "; it can never exceed %d", v.Limit)
	}
	if v.HasMin {
		fmt.Fprintf(&b, "; writes that would take it below %d fail", v.Min)
	}
	return b.String()
}

func predText(ps []*schema.Pred) string {
	var parts []string
	for _, p := range ps {
		parts = append(parts, fmt.Sprintf("%s = %v", p.Field.Name, fmtValue(p.Value)))
	}
	return strings.Join(parts, " and ")
}

func fmtValue(v any) string {
	if s, ok := v.(string); ok {
		return strconv.Quote(s)
	}
	return fmt.Sprint(v)
}

func goType(e *schema.Entity, f *schema.Field) string {
	switch f.Type {
	case schema.TypeEnum:
		return e.GoName + f.GoName
	case schema.TypeInt:
		return "int64"
	case schema.TypeFloat:
		return "float64"
	case schema.TypeBool:
		return "bool"
	case schema.TypeTime:
		return "time.Time"
	case schema.TypeBytes:
		return "[]byte"
	case schema.TypeStringSet, schema.TypeList:
		return "[]string"
	case schema.TypeMap:
		return "map[string]string"
	}
	return "string"
}

func tag(f *schema.Field, omitempty bool) string {
	t := f.Attr
	if f.Type == schema.TypeStringSet {
		t += ",set"
	}
	if omitempty {
		t += ",omitempty"
	}
	return t
}

// fmtExpr returns a format string with one %s for the receiver expression, rendering the field
// for use in a key. recv "" returns the raw pattern.
func fmtExpr(f *schema.Field, recv string) string {
	var pat string
	switch f.Type {
	case schema.TypeEnum:
		pat = "string(%s)"
	case schema.TypeInt:
		pat = "dynago.FmtInt(%s)"
	case schema.TypeBool:
		pat = "dynago.FmtBool(%s)"
	case schema.TypeTime:
		pat = "dynago.FmtTime(%s)"
	default:
		pat = "%s"
	}
	if recv == "" {
		return pat
	}
	return fmt.Sprintf(pat, recv)
}

// tmplExpr renders a key template as a Go string expression over recv's fields.
func tmplExpr(e *schema.Entity, t schema.Template, recv string) string {
	vals := map[string]string{}
	for _, f := range t.Fields {
		vals[f.Name] = recv + "." + f.GoName
	}
	return tmplExprVals(e, t, vals)
}

func tmplExprVals(e *schema.Entity, t schema.Template, vals map[string]string) string {
	var parts []string
	for _, s := range t.Segments {
		if !s.IsField() {
			parts = append(parts, strconv.Quote(s.Literal))
			continue
		}
		parts = append(parts, transformExpr(s.Transform, fmtExpr(e.Field(s.Field), vals[s.Field])))
	}
	return strings.Join(parts, " + ")
}

// transformExpr applies a key template transform to a rendered value expression.
func transformExpr(transform, expr string) string {
	if transform == "lower" {
		return "dynago.Lower(" + expr + ")"
	}
	return expr
}

// rangeTransform returns the transform on the sort key segment a range bounds.
func rangeTransform(sk schema.Template, field *schema.Field) string {
	for _, s := range sk.Segments {
		if s.Field == field.Name {
			return s.Transform
		}
	}
	return ""
}

// present returns a Go condition true when a sparse field holds a value, or "" for fields that
// are always present.
func present(f *schema.Field, expr string) string {
	switch f.Type {
	case schema.TypeString, schema.TypeEnum:
		return expr + ` != ""`
	case schema.TypeTime:
		return "!" + expr + ".IsZero()"
	}
	return ""
}

func presence(fields []*schema.Field, recv string) string {
	var conds []string
	for _, f := range fields {
		if c := present(f, recv+"."+f.GoName); c != "" {
			conds = append(conds, c)
		}
	}
	return strings.Join(conds, " && ")
}

func presenceAndWhere(e *schema.Entity, fields []*schema.Field, where []*schema.Pred, recv string) string {
	var conds []string
	if pc := presence(fields, recv); pc != "" {
		conds = append(conds, pc)
	}
	if len(where) > 0 {
		conds = append(conds, whereExpr(e, where, recv))
	}
	return orTrue(conds)
}

// negate negates a condition built by whereExpr or presence. A conjunction of simple comparisons
// is negated term by term (De Morgan), which reads better than !(...).
func negate(cond string) string {
	// Split only where no string literal (other than "") could itself contain " && ".
	if strings.Contains(cond, " && ") && !strings.Contains(cond, "||") && !strings.Contains(strings.ReplaceAll(cond, `""`, ""), `"`) {
		terms := strings.Split(cond, " && ")
		simple := true
		for i, t := range terms {
			terms[i] = negate(t)
			simple = simple && !strings.HasPrefix(terms[i], "!(")
		}
		if simple {
			return strings.Join(terms, " || ")
		}
	}
	if !strings.Contains(cond, "&&") {
		switch {
		case strings.HasPrefix(cond, "!") && !strings.HasPrefix(cond, "!("):
			return strings.TrimPrefix(cond, "!")
		case strings.Contains(cond, " == "):
			return strings.Replace(cond, " == ", " != ", 1)
		case strings.Contains(cond, " != "):
			return strings.Replace(cond, " != ", " == ", 1)
		case !strings.ContainsAny(cond, " ()"):
			return "!" + cond
		}
	}
	return "!(" + cond + ")"
}

func orTrue(conds []string) string {
	if len(conds) == 0 {
		return "true"
	}
	return strings.Join(conds, " && ")
}

func whereExpr(e *schema.Entity, ps []*schema.Pred, recv string) string {
	var conds []string
	for _, p := range ps {
		x := recv + "." + p.Field.GoName
		if b, ok := p.Value.(bool); ok {
			if b {
				conds = append(conds, x)
			} else {
				conds = append(conds, "!"+x)
			}
			continue
		}
		conds = append(conds, fmt.Sprintf("%s == %s", x, literal(e, p.Field, p.Value)))
	}
	return strings.Join(conds, " && ")
}

// literal renders a constant of a field's type.
func literal(e *schema.Entity, f *schema.Field, v any) string {
	switch f.Type {
	case schema.TypeEnum:
		return e.GoName + f.GoName + schema.GoName(v.(string))
	case schema.TypeString:
		return strconv.Quote(v.(string))
	case schema.TypeFloat:
		return strconv.FormatFloat(v.(float64), 'g', -1, 64)
	}
	return fmt.Sprint(v)
}

func isZeroValue(v any) bool {
	switch x := v.(type) {
	case bool:
		return !x
	case int64:
		return x == 0
	case float64:
		return x == 0
	case string:
		return x == ""
	}
	return false
}

// constSetLit renders a dynago.Set for a field set to a constant: a zero constant removes it.
func constSetLit(e *schema.Entity, f *schema.Field, v any) string {
	if isZeroValue(v) {
		return fmt.Sprintf("{Attr: %q, Remove: true}", f.Attr)
	}
	return fmt.Sprintf("{Attr: %q, Value: %s}", f.Attr, literal(e, f, v))
}

// zeroCond returns a Go condition true when val, of f's type, is the zero value.
func zeroCond(f *schema.Field, val string) string {
	switch f.Type {
	case schema.TypeString, schema.TypeEnum:
		return val + ` == ""`
	case schema.TypeInt, schema.TypeFloat:
		return val + " == 0"
	case schema.TypeBool:
		return "!" + val
	case schema.TypeTime:
		return val + ".IsZero()"
	}
	return "len(" + val + ") == 0"
}

// setLit renders a dynago.Set for a field given a value expression.
func setLit(f *schema.Field, val string) string {
	zero := zeroCond(f, val)
	set := ""
	if f.Type == schema.TypeStringSet {
		set = ", StringSet: true"
	}
	return fmt.Sprintf("{Attr: %q, Value: %s, Remove: %s%s}", f.Attr, val, zero, set)
}

func templateFields(pk, sk schema.Template, hasSK bool) []*schema.Field {
	out := append([]*schema.Field{}, pk.Fields...)
	if hasSK {
		for _, f := range sk.Fields {
			dup := false
			for _, o := range out {
				dup = dup || o == f
			}
			if !dup {
				out = append(out, f)
			}
		}
	}
	return out
}

func fieldList(fs []*schema.Field) string {
	var names []string
	for _, f := range fs {
		names = append(names, f.Name)
	}
	switch len(names) {
	case 0:
		return ""
	case 1:
		return names[0]
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

// taken are names a parameter must not use: the generated methods' own variables and the
// packages the generated file imports.
var taken = map[string]bool{
	"ctx": true, "s": true, "k": true, "v": true, "q": true, "o": true, "e": true, "opts": true,
	"claim": true, "claimKey": true, "found": true, "err": true, "it": true, "key": true,
	"context": true, "fmt": true, "time": true, "dynamo": true, "dynago": true,
}

// paramName names a method parameter after a field, avoiding keywords, predeclared identifiers
// (string, len, nil...) and the names in taken.
func paramName(f *schema.Field) string {
	name := lowerFirst(f.GoName)
	if token.IsKeyword(name) || types.Universe.Lookup(name) != nil || taken[name] {
		return name + "Value"
	}
	return name
}

func stringSlice(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func lowerFirst(s string) string {
	r := []rune(s)
	n := 0
	for n < len(r) && unicode.IsUpper(r[n]) {
		n++
	}
	// Lower a leading acronym as a unit, keeping the capital that starts the next word:
	// "Registration" → "registration", "URLMap" → "urlMap", "API" → "api".
	if n > 1 && n < len(r) {
		n--
	}
	for i := 0; i < n; i++ {
		r[i] = unicode.ToLower(r[i])
	}
	return string(r)
}

// lowerDocStart turns a schema doc into the continuation of a Go comment that starts with the
// identifier: a noun phrase with an article becomes "is a ...", anything else has its first letter
// lower-cased so that a verb reads naturally ("Lists ..." → "ListForUser lists ..."). Docs starting
// with an acronym are left alone.
func lowerDocStart(doc string) string {
	doc = strings.TrimSpace(doc)
	words := strings.Fields(doc)
	if len(words) == 0 {
		return doc
	}
	switch strings.ToLower(words[0]) {
	case "a", "an", "the", "one":
		return "is " + lowerInitial(doc)
	}
	r := []rune(words[0])
	if len(r) > 1 && unicode.IsUpper(r[1]) {
		return doc
	}
	return lowerInitial(doc)
}

func lowerInitial(s string) string {
	r := []rune(s)
	if len(r) > 0 {
		r[0] = unicode.ToLower(r[0])
	}
	return string(r)
}

// article returns "a" or "an" for a word, by how it usually sounds: "an Event", "a User",
// "a Unique…", "an Update".
func article(word string) string {
	w := strings.ToLower(word)
	if w == "" || !strings.ContainsRune("aeiou", rune(w[0])) {
		return "a"
	}
	// A "u" said "you" (user, unique, usage): u, consonant, vowel.
	if w[0] == 'u' && len(w) > 2 && !strings.ContainsRune("aeiou", rune(w[1])) && strings.ContainsRune("aeiou", rune(w[2])) {
		return "a"
	}
	return "an"
}

// comment writes text as a wrapped // comment.
func comment(buf *bytes.Buffer, text string) {
	for i, para := range strings.Split(text, "\n\n") {
		if i > 0 {
			buf.WriteString("//\n")
		}
		line := "//"
		for _, w := range strings.Fields(para) {
			if len(line)+1+len(w) > 100 && line != "//" {
				buf.WriteString(line + "\n")
				line = "//"
			}
			line += " " + w
		}
		buf.WriteString(line + "\n")
	}
}

// uniqueVals maps the fields of a unique constraint to value expressions: recv's fields, and elem
// for the set field.
func uniqueVals(u *schema.Unique, recv, elem string) map[string]string {
	vals := map[string]string{}
	for _, f := range u.Fields {
		vals[f.Name] = recv + "." + f.GoName
	}
	if u.Set != nil {
		vals[u.Set.Name] = elem
	}
	return vals
}
