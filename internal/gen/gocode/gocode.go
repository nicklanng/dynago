func (g *gen) write(w *schema.Write) {
	switch w.Kind {
	case schema.WriteCreate:
		g.create(w)
	case schema.WriteUpdate:
		g.update(w)
	case schema.WriteDelete:
		g.delete(w)
	}
}

func (g *gen) limitsArg(w *schema.Write) (param, conv string) {
	e := w.Entity
	lo := lowerFirst(e.GoName)
	if !hasLimitArgs(e) {
		return "", ""
	}
	if len(w.Limits) == 0 {
		return "", fmt.Sprintf(", %sLimits{}", lo)
	}
	var fs []string
	for _, v := range w.Limits {
		n := v.Counter.GoName + v.GoName
		fs = append(fs, fmt.Sprintf("%s: limits.%s", n, n))
	}
	return fmt.Sprintf(", limits %s%sLimits", e.GoName, w.GoName), fmt.Sprintf(", %sLimits{%s}", lo, strings.Join(fs, ", "))
}

// requireLimits emits a check that every caller-supplied limit was given: a forgotten limit must
// not silently switch enforcement off.
func (g *gen) requireLimits(w *schema.Write, ret string) {
	for _, v := range w.Limits {
		n := v.Counter.GoName + v.GoName
		g.p("if err := dynago.RequireLimit(%q, limits.%s); err != nil {", w.Entity.GoName+w.GoName+"Limits."+n, n)
		g.p("%s", ret)
		g.p("}")
	}
}

func (g *gen) create(w *schema.Write) {
	e := w.Entity
	lo := lowerFirst(e.GoName)
	param, conv := g.limitsArg(w)
	var desc strings.Builder
	fmt.Fprintf(&desc, "creates %s %s, failing with Err%sExists if one already exists", article(e.Name), e.Name, e.GoName)
	if e.TTL != nil {
		desc.WriteString(" (an expired one is replaced)")
	}
	desc.WriteString(".")
	if len(w.Sets) > 0 {
		fmt.Fprintf(&desc, " It sets %s, whatever e holds.", schema.SetText(w.Sets, e.Name))
	}
	if req := requiredFields(e); len(req) > 0 {
		fmt.Fprintf(&desc, " %s must be set (else dynago.ErrFieldRequired).", capitalise(fieldList(req)))
	}
	desc.WriteString(requiresText(w))
	desc.WriteString(maintains(e))
	desc.WriteString(" Afterwards e.Version() returns the new item's version.")
	g.docComment(w.GoName, w.Doc, desc.String())
	g.p("func (s *%sStore) %s(ctx context.Context, e *%s%s) error {", e.GoName, w.GoName, e.GoName, param)
	for _, sc := range w.Sets {
		g.p("e.%s = %s", sc.Field.GoName, literal(e, sc.Field, sc.Value))
	}
	g.p("key, err := e.Key().dynamoKey()")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.requireLimits(w, "return err")
	g.requiredChecks(e, e.Fields, "e", "return err")
	g.p("if err := e.checkKeyParts(); err != nil {")
	g.p("return err")
	g.p("}")
	g.p("rev := dynago.NewRev()")
	g.p("return dynago.Retry(ctx, func() error {")
	tw := hasTargetWrites(w)
	if tw {
		g.p("err := dynago.ReadIfNeeded(func(read bool) error {")
	}
	if e.TTL != nil {
		g.p("put := s.t.Put(%sToItem(e, key, rev)).If(\"attribute_not_exists($) OR $ <= ?\", \"PK\", %q, dynago.Now())", lo, g.m.Table.TTLAttr)
	} else {
		g.p("put := s.t.Put(%sToItem(e, key, rev)).If(\"attribute_not_exists($)\", \"PK\")", lo)
	}
	g.p("ops := []dynago.Op{dynago.CreateOp(key, put, Err%sExists, rev)}", e.GoName)
	own := ""
	if e.HasDerived() {
		own = fmt.Sprintf("dynago.Change{Owner: key, After: %sDerived(e, key, %sVersion%s)}", lo, lo, conv)
	}
	g.requiresAndDerived(w, "e", "read", own)
	if tw {
		g.p("return dynago.Run(ctx, s.db, ops)")
		g.p("})")
		g.p("if err != nil {")
	} else {
		g.p("if err := dynago.Run(ctx, s.db, ops); err != nil {")
	}
	g.p("return err")
	g.p("}")
	g.p("e.loaded = &%sLoaded{rev: rev, v: %sVersion, snapshot: e.clone()}", lo, lo)
	g.p("return nil")
	g.p("})")
	g.p("}")
	g.p("")
}

// requiredFields returns the non-key fields declared required (key fields are always required).
func requiredFields(e *schema.Entity) []*schema.Field {
	var out []*schema.Field
	for _, f := range e.Fields {
		if f.Required && !f.Key {
			out = append(out, f)
		}
	}
	return out
}

func capitalise(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// patchFastPath returns the patch fields of a read-first update that are its only reason to read:
// when the caller leaves all of them nil, the update can run as a single UpdateItem. It returns
// nil if the update reads for any other reason.
func patchFastPath(w *schema.Write) []*schema.Field {
	if w.Kind != schema.WriteUpdate || !w.ReadFirst || len(w.Requires) > 0 {
		return nil
	}
	inputs := w.Entity.DerivedInputs()
	for _, f := range w.Args {
		if inputs[f.Name] {
			return nil
		}
	}
	for _, s := range w.Sets {
		if inputs[s.Field.Name] {
			return nil
		}
	}
	var slow []*schema.Field
	for _, f := range w.Patch {
		if inputs[f.Name] {
			slow = append(slow, f)
		}
	}
	return slow
}

// updateSets emits the sets list for an update's arguments, patch fields and constants. Patch
// fields in skip are known to be nil and are left out.
func (g *gen) updateSets(w *schema.Write, skip ...*schema.Field) {
	e := w.Entity
	g.p("sets := []dynago.Set{")
	for _, f := range w.Args {
		g.p("%s,", setLit(f, "v."+f.GoName))
	}
	for _, s := range w.Sets {
		g.p("%s,", constSetLit(e, s.Field, s.Value))
	}
	g.p("}")
	skipped := map[*schema.Field]bool{}
	for _, f := range skip {
		skipped[f] = true
	}
	for _, f := range w.Patch {
		if skipped[f] {
			continue
		}
		g.p("if v.%s != nil {", f.GoName)
		g.p("sets = append(sets, dynago.Set%s)", setLit(f, "*v."+f.GoName))
		g.p("}")
	}
	if e.TTL != nil {
		for _, f := range w.Changed() {
			if f != e.TTL || skipped[f] {
				continue
			}
			val, patch := "v."+f.GoName, false
			for _, s := range w.Sets {
				if s.Field == f {
					val = literal(e, f, s.Value)
				}
			}
			for _, pf := range w.Patch {
				patch = patch || pf == f
			}
			if patch {
				g.p("if v.%s != nil {", f.GoName)
				val = "(*v." + f.GoName + ")"
			}
			g.p("sets = append(sets, dynago.Set{Attr: %q, Value: dynago.UnixTTL(%s), Remove: %s.IsZero()})", g.m.Table.TTLAttr, val, val)
			if patch {
				g.p("}")
			}
		}
	}
}

// applyChanges emits assignments of an update's changes onto after.
func (g *gen) applyChanges(w *schema.Write) {
	e := w.Entity
	for _, f := range w.Args {
		g.p("after.%s = v.%s", f.GoName, f.GoName)
	}
	for _, f := range w.Patch {
		g.p("if v.%s != nil {", f.GoName)
		g.p("after.%s = *v.%s", f.GoName, f.GoName)
		g.p("}")
	}
	for _, s := range w.Sets {
		g.p("after.%s = %s", s.Field.GoName, literal(e, s.Field, s.Value))
	}
}

func (g *gen) update(w *schema.Write) {
	e := w.Entity
	lo := lowerFirst(e.GoName)
	argType := e.GoName + w.GoName
	hasV := len(w.Args)+len(w.Patch) > 0
	if hasV {
		g.p("// %s holds the new values for %s.%s.", argType, e.Name, w.Name)
		if len(w.Patch) > 0 {
			g.p("// Pointer fields are optional: nil leaves the field as it is, a pointer to the zero value clears it.")
		}
		g.p("type %s struct {", argType)
		for _, f := range w.Args {
			g.p("%s %s", f.GoName, goType(e, f))
		}
		for _, f := range w.Patch {
			g.p("%s *%s", f.GoName, goType(e, f))
		}
		g.p("}")
		g.p("")
	}
	param, conv := g.limitsArg(w)
	slowPatch := patchFastPath(w)
	var desc strings.Builder
	fmt.Fprintf(&desc, "updates %s of %s %s", fieldList(w.Changed()), article(e.Name), e.Name)
	if len(w.When) > 0 {
		fmt.Fprintf(&desc, " when %s (else Err%s%sPrecondition)", predText(w.When), e.GoName, w.GoName)
	}
	switch {
	case w.Transition:
		reason := affected(w)
		if reason == "" {
			reason = "the items it requires"
		}
		fmt.Fprintf(&desc, ". The change to %s is known from the arguments, so it runs without reading the item: conditional writes in one transaction. If the item is not in the state assumed, it falls back to reading it.%s", reason, maintains(e))
	case w.ReadFirst && (e.HasDerived() || len(w.Requires) > 0):
		reason := affected(w)
		if reason == "" {
			reason = "what it requires"
		}
		fmt.Fprintf(&desc, ". It reads the item consistently first (not with dynago.From) because the change affects %s, then writes everything in one transaction guarded by the item's revision.%s", reason, maintains(e))
	case w.ReadFirst:
		fmt.Fprintf(&desc, ". It reads the item consistently first (not with dynago.From) because the change affects %s, then rewrites it with one PutItem guarded by the item's revision.", affected(w))
	default:
		desc.WriteString(" with a single conditional UpdateItem.")
	}
	if len(slowPatch) > 0 {
		fmt.Fprintf(&desc, " A call that leaves %s nil changes nothing derived, and runs as a single conditional UpdateItem instead.", fieldList(slowPatch))
	}
	var required []*schema.Field
	for _, f := range w.Changed() {
		if f.Required {
			required = append(required, f)
		}
	}
	if len(required) > 0 {
		fmt.Fprintf(&desc, " %s may not be set to the zero value (dynago.ErrFieldRequired).", capitalise(fieldList(required)))
	}
	desc.WriteString(requiresText(w))
	g.docComment(w.GoName, w.Doc, desc.String())
	vparam := ""
	if hasV {
		vparam = fmt.Sprintf(", v %s", argType)
	}
	g.p("func (s *%sStore) %s(ctx context.Context, k %sKey%s%s, opts ...dynago.WriteOption) error {", e.GoName, w.GoName, e.GoName, vparam, param)
	g.p("key, err := k.dynamoKey()")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.requireLimits(w, "return err")
	g.requiredChecks(e, w.Args, "v", "return err")
	for _, f := range w.Patch {
		if f.Required {
			g.p("if v.%s != nil && %s {", f.GoName, zeroCond(f, "*v."+f.GoName))
			g.p("return fmt.Errorf(\"%%w: %s.%s\", dynago.ErrFieldRequired)", e.Name, f.Name)
			g.p("}")
		}
	}
	g.p("o := dynago.ApplyOptions(opts)")
	if len(w.Args)+len(w.Sets) == 0 {
		var nils []string
		for _, f := range w.Patch {
			nils = append(nils, "v."+f.GoName+" == nil")
		}
		g.p("if %s {", strings.Join(nils, " && "))
		g.p("return nil // nothing to change")
		g.p("}")
	}
	precond := "nil"
	if len(w.When) > 0 {
		precond = fmt.Sprintf("Err%s%sPrecondition", e.GoName, w.GoName)
	}
	var conds []string
	for _, p := range w.When {
		conds = append(conds, fmt.Sprintf("{Attr: %q, Value: %s, Zero: %t}", p.Field.Attr, literal(e, p.Field, p.Value), isZeroValue(p.Value)))
	}
	when := "nil"
	if len(conds) > 0 {
		when = "[]dynago.Cond{" + strings.Join(conds, ", ") + "}"
	}
	if !w.ReadFirst || len(slowPatch) > 0 {
		if len(slowPatch) > 0 {
			var nils []string
			for _, f := range slowPatch {
				nils = append(nils, "v."+f.GoName+" == nil")
			}
			g.p("if %s {", strings.Join(nils, " && "))
			g.p("// Nothing derived changes: one conditional UpdateItem, no read.")
		}
		g.changedKeyPartChecks(w, slowPatch...)
		g.updateSets(w, slowPatch...)
		g.p("guard, err := s.guard(key, o, %t)", w.VersionRequired)
		g.p("if err != nil {")
		g.p("return err")
		g.p("}")
		g.p("return dynago.Retry(ctx, func() error {")
		g.p("rev, err := dynago.UpdateFields(ctx, s.t, key, sets, %s, guard, %s)", when, precond)
		g.p("if err == nil {")
		g.p("o.Written(rev)")
		g.p("}")
		g.p("return dynago.StaleAs(guard.ExpectRev != 0, err)")
		g.p("})")
		if len(slowPatch) == 0 {
			g.p("}")
			g.p("")
			return
		}
		g.p("}")
	}
	beforeConv := ""
	if hasLimitArgs(e) {
		beforeConv = fmt.Sprintf(", %sLimits{}", lo)
	}
	if w.Transition {
		g.transition(w, when, beforeConv, conv)
	}
	g.p("return dynago.Retry(ctx, func() error {")
	g.p("it, versioned, err := s.start(ctx, key, o, %t)", w.VersionRequired)
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.newerGuard(e)
	g.p("before := &it.%s", e.GoName)
	if len(w.When) > 0 {
		g.p("if %s {", negate(whereExpr(e, w.When, "before")))
		g.p("return %s", precond)
		g.p("}")
	}
	g.p("after := before.clone()")
	g.applyChanges(w)
	g.changedKeyPartChecks(w)
	g.p("ops := []dynago.Op{dynago.PutOp(key, s.t.Put(%sToItem(&after, key, it.Rev+1)).If(\"$ = ? AND (attribute_not_exists($) OR $ <= ?)\", \"_rev\", it.Rev, \"_v\", \"_v\", %sVersion), dynago.ErrStale)}", lo, lo)
	own := ""
	if e.HasDerived() {
		own = fmt.Sprintf("dynago.Change{Owner: key, Before: %sDerived(before, key, it.V%s), After: %sDerived(&after, key, %sVersion%s)}", lo, beforeConv, lo, lo, conv)
	}
	g.runWithRequires(w, "after", own, func() {
		g.p("o.Written(it.Rev + 1)")
	})
	g.p("})")
	g.p("}")
	g.p("")
}

// runWithRequires emits the end of a read-first write: its requires, its derived writes, the
// transaction, and done on success. own is the write's own dynago.Change ("" if it has none). A
// write that changes other items builds those changes in a closure run by dynago.ReadIfNeeded,
// so it can try without reading them and fall back to reading.
func (g *gen) runWithRequires(w *schema.Write, recv, own string, done func()) {
	if !hasTargetWrites(w) {
		g.requiresAndDerived(w, recv, "false", own)
		g.p("if err := dynago.Run(ctx, s.db, ops); err != nil {")
		g.p("return dynago.StaleAs(versioned, err)")
		g.p("}")
		done()
		g.p("return nil")
		return
	}
	g.p("base := ops")
	g.p("return dynago.StaleAs(versioned, dynago.ReadIfNeeded(func(read bool) error {")
	g.p("ops := append([]dynago.Op(nil), base...)")
	g.requiresAndDerived(w, recv, "read", own)
	g.p("if err := dynago.Run(ctx, s.db, ops); err != nil {")
	g.p("return err")
	g.p("}")
	done()
	g.p("return nil")
	g.p("}))")
}

// requiresAndDerived emits a write's requires, then one diff of every derived change in the
// transaction: the write's own (own, a dynago.Change expression, or "") and those of the other
// entities its requires change. Diffing them together merges changes to a shared counter item,
// which a transaction may touch only once.
func (g *gen) requiresAndDerived(w *schema.Write, recv, read, own string) {
	if own == "" && !hasTargetWrites(w) {
		g.requireOps(w, recv, read)
		return
	}
	if own != "" {
		g.p("changes := []dynago.Change{%s}", strings.TrimPrefix(own, "dynago.Change"))
	} else {
		g.p("var changes []dynago.Change")
	}
	g.requireOps(w, recv, read)
	g.p("derived, err := dynago.DiffAll(s.t, changes)")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.p("ops = append(ops, derived...)")
}

// transition emits the read-free attempt of an update whose derived changes are known from its
// arguments: the item's update, conditioned on the state assumed, plus the derived writes.
func (g *gen) transition(w *schema.Write, when, beforeConv, conv string) {
	e := w.Entity
	lo := lowerFirst(e.GoName)
	var known []string
	for _, f := range e.KeyFields() {
		known = append(known, fmt.Sprintf("%s: k.%s", f.GoName, f.GoName))
	}
	for _, p := range w.When {
		known = append(known, fmt.Sprintf("%s: %s", p.Field.GoName, literal(e, p.Field, p.Value)))
	}
	g.p("// The derived changes depend only on the key and the state `when` pins, so try without")
	g.p("// reading. ReturnVersion and dynago.From need the read path.")
	g.p("if o.From == nil && o.NewVersion == nil {")
	g.p("expect, err := o.ExpectedRev()")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	if w.VersionRequired {
		g.p("if expect == 0 {")
		g.p("return dynago.ErrVersionRequired")
		g.p("}")
	}
	g.p("err = dynago.Retry(ctx, func() error {")
	g.p("before := %s{%s}", e.GoName, strings.Join(known, ", "))
	g.p("after := before.clone()")
	g.applyChanges(w)
	g.changedKeyPartChecks(w)
	g.updateSets(w)
	g.p("u := s.t.Update(\"PK\", key.PK).Range(\"SK\", key.SK)")
	g.p("dynago.SetFields(u, sets)")
	ttl := ""
	if e.TTL != nil {
		ttl = fmt.Sprintf(", TTLAttr: %q", g.m.Table.TTLAttr)
	}
	g.p("dynago.GuardUpdate(u, dynago.Guard{ExpectRev: expect, Version: %sVersion%s}, dynago.Now())", lo, ttl)
	if e.HasDerived() {
		g.p("dynago.AtLeastVersion(u, %d)", derivedSince(e))
	}
	if len(w.When) > 0 {
		g.p("for _, c := range %s {", when)
		g.p("dynago.CondUpdate(u, c)")
		g.p("}")
	}
	g.p("ops := []dynago.Op{dynago.UpdateOp(key, u, dynago.ErrNeedsRead)}")
	own := ""
	if e.HasDerived() {
		own = fmt.Sprintf("dynago.Change{Owner: key, Before: %sDerived(&before, key, %sVersion%s), After: %sDerived(&after, key, %sVersion%s)}", lo, lo, beforeConv, lo, lo, conv)
	}
	// Other items are assumed to be in the state required too; any doubt goes to the read path.
	g.requiresAndDerived(w, "after", "false", own)
	g.p("return dynago.Run(ctx, s.db, ops)")
	g.p("})")
	g.p("if !dynago.NeedsRead(err) {")
	g.p("return err")
	g.p("}")
	g.p("// The item was absent, not in the assumed state, or older: the read path reports which.")
	g.p("}")
}

func (g *gen) delete(w *schema.Write) {
	e := w.Entity
	lo := lowerFirst(e.GoName)
	if !w.ReadFirst {
		g.docComment(w.GoName, w.Doc, fmt.Sprintf("deletes %s %s with one conditional DeleteItem, failing with Err%sNotFound if it is absent.", article(e.Name), e.Name, e.GoName))
		g.p("func (s *%sStore) %s(ctx context.Context, k %sKey, opts ...dynago.WriteOption) error {", e.GoName, w.GoName, e.GoName)
		g.p("key, err := k.dynamoKey()")
		g.p("if err != nil {")
		g.p("return err")
		g.p("}")
		g.p("guard, err := s.guard(key, dynago.ApplyOptions(opts), %t)", w.VersionRequired)
		g.p("if err != nil {")
		g.p("return err")
		g.p("}")
		g.p("return dynago.Retry(ctx, func() error {")
		g.p("return dynago.StaleAs(guard.ExpectRev != 0, dynago.DeleteIfExists(ctx, s.t, key, guard))")
		g.p("})")
		g.p("}")
		g.p("")
		return
	}
	g.docComment(w.GoName, w.Doc, fmt.Sprintf("deletes %s %s, failing with Err%sNotFound if it is absent. It reads the item consistently first (not with dynago.From) so it can release what the item contributed, then writes everything in one transaction guarded by the item's revision.%s%s",
		article(e.Name), e.Name, e.GoName, requiresText(w), maintains(e)))
	g.p("func (s *%sStore) %s(ctx context.Context, k %sKey, opts ...dynago.WriteOption) error {", e.GoName, w.GoName, e.GoName)
	g.p("key, err := k.dynamoKey()")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.p("o := dynago.ApplyOptions(opts)")
	g.p("return dynago.Retry(ctx, func() error {")
	g.p("it, versioned, err := s.start(ctx, key, o, %t)", w.VersionRequired)
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.newerGuard(e)
	g.p("ops := []dynago.Op{dynago.DeleteOp(key, s.t.Delete(\"PK\", key.PK).Range(\"SK\", key.SK).If(\"$ = ? AND (attribute_not_exists($) OR $ <= ?)\", \"_rev\", it.Rev, \"_v\", \"_v\", %sVersion), dynago.ErrStale)}", lo)
	own := ""
	if e.HasDerived() {
		beforeConv := ""
		if hasLimitArgs(e) {
			beforeConv = fmt.Sprintf(", %sLimits{}", lo)
		}
		own = fmt.Sprintf("dynago.Change{Owner: key, Before: %sDerived(&it.%s, key, it.V%s)}", lo, e.GoName, beforeConv)
	}
	if len(w.Requires) > 0 {
		g.p("e := &it.%s", e.GoName)
	}
	g.runWithRequires(w, "e", own, func() {})
	g.p("})")
	g.p("}")
	g.p("")
}

