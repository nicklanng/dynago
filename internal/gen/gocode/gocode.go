// Package gocode generates the typed Go store for a schema.
package gocode

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"github.com/nicklanng/dynago/internal/gen/infra"
	"github.com/nicklanng/dynago/internal/schema"
)

// Generate returns the formatted Go source for the model. source is the schema path recorded in
// the header.
func Generate(m *schema.Model, source string) ([]byte, error) {
	g := &gen{m: m}
	g.file(source)
	out, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("gocode: generated code does not parse (this is a dynago bug): %w", err)
	}
	return out, nil
}

type gen struct {
	m    *schema.Model
	buf  bytes.Buffer
	seps map[*schema.Field]string // see separators
}

func (g *gen) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *gen) file(source string) {
	m := g.m
	g.p("// Code generated by dynago from %s. DO NOT EDIT.", source)
	g.p("")
	g.p("package %s", m.Package)
	g.p("")
	g.p("import (")
	g.p(`"context"`)
	g.p(`"fmt"`)
	if g.usesTime() {
		g.p(`"time"`)
	}
	g.p("")
	g.p(`"github.com/guregu/dynamo/v2"`)
	g.p("")
	g.p(`"github.com/nicklanng/dynago"`)
	g.p(")")
	g.p("")
	g.tableSpec()
	g.store()
	for _, e := range m.Entities {
		g.entity(e)
	}
}

func (g *gen) usesTime() bool {
	for _, e := range g.m.Entities {
		for _, f := range e.Fields {
			if f.Type == schema.TypeTime {
				return true
			}
		}
	}
	return false
}

func (g *gen) tableSpec() {
	spec := infra.Spec(g.m)
	g.p("// TableSpec is the physical shape of the %s table: base key PK/SK, its global secondary", g.m.Table.Name)
	g.p("// indexes and its TTL attribute. See also the generated Terraform.")
	g.p("var TableSpec = dynago.TableSpec{")
	if spec.TTLAttr != "" {
		g.p("TTLAttr: %q,", spec.TTLAttr)
	}
	if len(spec.GSIs) > 0 {
		g.p("GSIs: []dynago.GSISpec{")
		for _, gs := range spec.GSIs {
			attrs := ""
			if len(gs.NonKeyAttrs) > 0 {
				attrs = fmt.Sprintf(", NonKeyAttrs: %s", stringSlice(gs.NonKeyAttrs))
			}
			g.p("{Name: %q, PKAttr: %q, SKAttr: %q, Projection: %q%s},", gs.Name, gs.PKAttr, gs.SKAttr, gs.Projection, attrs)
		}
		g.p("},")
	}
	g.p("}")
	g.p("")
}

func (g *gen) store() {
	m := g.m
	if m.Table.Doc != "" {
		comment(&g.buf, fmt.Sprintf("Store gives typed access to the %s table. %s", m.Table.Name, m.Table.Doc))
	} else {
		g.p("// Store gives typed access to the %s table.", m.Table.Name)
	}
	g.p("type Store struct {")
	for _, e := range m.Entities {
		g.p("%s *%sStore", schema.Plural(e.GoName), e.GoName)
	}
	g.p("}")
	g.p("")
	g.p("// New returns a Store for the table named tableName.")
	g.p("func New(db *dynamo.DB, tableName string) *Store {")
	g.p("t := db.Table(tableName)")
	g.p("return &Store{")
	for _, e := range m.Entities {
		g.p("%s: &%sStore{db: db, t: t},", schema.Plural(e.GoName), e.GoName)
	}
	g.p("}")
	g.p("}")
	g.p("")
	g.p("// EnsureTable creates the table if it is missing and enables TTL. Use it for local")
	g.p("// development and tests; production tables belong in infrastructure code.")
	g.p("func EnsureTable(ctx context.Context, db *dynamo.DB, tableName string) error {")
	g.p("return dynago.EnsureTable(ctx, db, tableName, TableSpec)")
	g.p("}")
	g.p("")
}

// ---- entity ----

func (g *gen) entity(e *schema.Entity) {
	lo := lowerFirst(e.GoName)
	g.p("// ---- %s ----", e.Name)
	g.p("")
	for _, f := range e.Fields {
		if f.Type == schema.TypeEnum {
			g.enum(e, f)
		}
	}

	// Entity struct.
	comment(&g.buf, typeDoc(e.GoName, e.Doc, fmt.Sprintf("is stored in the %s table.", g.m.Table.Name)))
	g.p("type %s struct {", e.GoName)
	for _, f := range e.Fields {
		if f.Doc != "" {
			comment(&g.buf, f.Doc)
		}
		g.p("%s %s `dynamo:\"%s\"`", f.GoName, goType(e, f), tag(f, !f.Key))
	}
	g.p("")
	g.p("loaded *%sLoaded // set when the store returns the entity", lowerFirst(e.GoName))
	g.p("}")
	g.p("")
	g.p("// %sLoaded remembers the stored state an entity was read at, so a write passed the entity", lowerFirst(e.GoName))
	g.p("// with dynago.From can start from it without reading again.")
	g.p("type %sLoaded struct {", lowerFirst(e.GoName))
	g.p("rev      int64")
	g.p("v        int")
	g.p("snapshot %s", e.GoName)
	g.p("}")
	g.p("")
	g.p("// Version identifies the stored state e was read at, for optimistic concurrency: pass it back")
	g.p("// with dynago.IfVersion (e.g. from an ETag) to make a write fail if anything changed since.")
	g.p("// It is \"\" for an entity that was not read from the store.")
	g.p("func (e *%s) Version() string {", e.GoName)
	g.p("if e.loaded == nil {")
	g.p("return \"\"")
	g.p("}")
	g.p("return dynago.FormatVersion(e.loaded.rev)")
	g.p("}")
	g.p("")
	g.clone(e)
	g.checkKeyParts(e)

	// Key struct.
	g.p("// %sKey identifies %s %s.", e.GoName, article(e.GoName), e.GoName)
	g.p("type %sKey struct {", e.GoName)
	for _, f := range e.KeyFields() {
		g.p("%s %s", f.GoName, goType(e, f))
	}
	g.p("}")
	g.p("")
	g.p("// Key returns the primary key of e.")
	g.p("func (e *%s) Key() %sKey {", e.GoName, e.GoName)
	var kv []string
	for _, f := range e.KeyFields() {
		kv = append(kv, fmt.Sprintf("%s: e.%s", f.GoName, f.GoName))
	}
	g.p("return %sKey{%s}", e.GoName, strings.Join(kv, ", "))
	g.p("}")
	g.p("")
	g.p("func (k %sKey) dynamoKey() (dynago.Key, error) {", e.GoName)
	g.presenceGuard(e.KeyFields(), "k", fmt.Sprintf("return dynago.Key{}, fmt.Errorf(\"%%w: %s needs %s\", dynago.ErrInvalidKey)", e.Name, fieldList(e.KeyFields())))
	g.keyPartChecks(e.KeyFields(), func(f *schema.Field) string { return "k." + f.GoName }, "return dynago.Key{}, err")
	g.p("return dynago.Key{PK: %s, SK: %s}, nil", tmplExpr(e, e.PK, "k"), tmplExpr(e, e.SK, "k"))
	g.p("}")
	g.p("")

	g.errors(e)

	// Item struct.
	g.p("const %sVersion = %d", lo, e.Version)
	g.p("")
	g.p("type %sItem struct {", lo)
	g.p("%s", e.GoName)
	g.p("PK string `dynamo:\"PK\"`")
	g.p("SK string `dynamo:\"SK\"`")
	g.p("T string `dynamo:\"_t\"`")
	g.p("V int `dynamo:\"_v\"`")
	g.p("Rev int64 `dynamo:\"_rev\"`")
	for _, ix := range e.Indexes {
		if ix.Strategy != schema.StrategyGSI {
			continue
		}
		g.p("%s string `dynamo:\"%s,omitempty\"`", ix.PKAttr, ix.PKAttr)
		if ix.HasSK {
			g.p("%s string `dynamo:\"%s,omitempty\"`", ix.SKAttr, ix.SKAttr)
		}
	}
	if e.TTL != nil {
		g.p("TTL int64 `dynamo:\"%s,omitempty\"`", g.m.Table.TTLAttr)
	}
	g.p("}")
	g.p("")
	g.p("func %sToItem(e *%s, key dynago.Key, rev int64) *%sItem {", lo, e.GoName, lo)
	g.p("it := &%sItem{%s: *e, PK: key.PK, SK: key.SK, T: %q, V: %sVersion, Rev: rev}", lo, e.GoName, e.Name, lo)
	for _, ix := range e.Indexes {
		if ix.Strategy != schema.StrategyGSI {
			continue
		}
		cond := presenceAndWhere(e, templateFields(ix.PK, ix.SK, ix.HasSK), ix.Where, "e")
		g.p("if %s {", cond)
		g.p("it.%s = %s", ix.PKAttr, tmplExpr(e, ix.PK, "e"))
		if ix.HasSK {
			g.p("it.%s = %s", ix.SKAttr, tmplExpr(e, ix.SK, "e"))
		}
		g.p("}")
	}
	if e.TTL != nil {
		g.p("it.TTL = dynago.UnixTTL(e.%s)", e.TTL.GoName)
	}
	g.p("return it")
	g.p("}")
	g.p("")

	g.views(e)
	g.counters(e)
	g.limits(e)
	if e.HasDerived() {
		g.derived(e)
	}

	// Store.
	g.p("// %sStore reads and writes %s items. Only the access patterns declared in the schema", e.GoName, e.GoName)
	g.p("// exist as methods.")
	g.p("type %sStore struct {", e.GoName)
	g.p("db *dynamo.DB")
	g.p("t  dynamo.Table")
	g.p("}")
	g.p("")
	g.p("func (s *%sStore) load(ctx context.Context, key dynago.Key, consistent bool) (*%sItem, error) {", e.GoName, lo)
	g.p("var raw dynamo.Item")
	g.p("found, err := dynago.GetOne(ctx, s.t, key, consistent, &raw)")
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("if !found {")
	g.p("return nil, Err%sNotFound", e.GoName)
	g.p("}")
	if e.TTL != nil {
		g.p("it, err := %sDecode(raw)", lo)
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("// DynamoDB deletes expired items lazily, often hours later: treat them as gone.")
		g.p("if dynago.Expired(it.TTL, dynago.Now()) {")
		g.p("return nil, Err%sNotFound", e.GoName)
		g.p("}")
		g.p("return it, nil")
	} else {
		g.p("return %sDecode(raw)", lo)
	}
	g.p("}")
	g.p("")
	g.p("// %sDecode decodes a stored item, remembering its state for writes passed dynago.From.", lo)
	g.p("func %sDecode(raw dynamo.Item) (*%sItem, error) {", lo, lo)
	g.p("var it %sItem", lo)
	g.p("if err := dynamo.UnmarshalItem(raw, &it); err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("it.loaded = &%sLoaded{rev: it.Rev, v: it.V, snapshot: it.clone()}", lo)
	g.p("return &it, nil")
	g.p("}")
	g.p("")
	g.p("func %sDecodeAll(raws []dynamo.Item) ([]%s, error) {", lo, e.GoName)
	g.p("out := make([]%s, 0, len(raws))", e.GoName)
	g.p("for _, raw := range raws {")
	g.p("it, err := %sDecode(raw)", lo)
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("out = append(out, it.%s)", e.GoName)
	g.p("}")
	g.p("return out, nil")
	g.p("}")
	g.p("")
	if hasVersionedWrites(e) {
		g.versionHelpers(e)
	}
	for _, a := range e.Access {
		g.access(a)
	}
	for _, w := range e.Writes {
		g.write(w)
	}
	g.requireFuncs(e)
}

func (g *gen) enum(e *schema.Entity, f *schema.Field) {
	name := e.GoName + f.GoName
	g.p("// %s is the set of values of %s.%s.", name, e.Name, f.Name)
	g.p("type %s string", name)
	g.p("")
	g.p("// Values of %s.", name)
	g.p("const (")
	for _, v := range f.Enum {
		g.p("%s%s %s = %q", name, schema.GoName(v), name, v)
	}
	g.p(")")
	g.p("")
}

func (g *gen) errors(e *schema.Entity) {
	g.p("// Errors returned by %sStore. Each wraps the matching dynago sentinel.", e.GoName)
	g.p("var (")
	g.p("Err%sNotFound = fmt.Errorf(\"%%w: %s\", dynago.ErrNotFound)", e.GoName, e.Name)
	g.p("Err%sExists = fmt.Errorf(\"%%w: %s\", dynago.ErrExists)", e.GoName, e.Name)
	for _, w := range e.Writes {
		if len(w.When) > 0 {
			g.p("Err%s%sPrecondition = fmt.Errorf(%s, dynago.ErrPrecondition)",
				e.GoName, w.GoName, errFormat(e.Name+"."+w.Name+" requires "+predText(w.When)))
		}
	}
	for _, w := range e.Writes {
		for _, rq := range w.Requires {
			if rq.CanFail() {
				g.p("%s = fmt.Errorf(%s, dynago.ErrPrecondition)", rq.ErrName, errFormat(e.Name+"."+w.Name+" requires "+rq.Condition(e.Name)))
			}
		}
	}
	for _, u := range e.Uniques {
		g.p("%s = fmt.Errorf(\"%%w: %s.%s\", dynago.ErrTaken)", u.ErrName, e.Name, u.Name)
	}
	for _, c := range e.Counters {
		for _, v := range c.Values {
			if v.Limited() {
				g.p("%s = fmt.Errorf(\"%%w: %s.%s\", dynago.ErrLimit)", v.ErrName, c.Name, v.Name)
			}
			if v.HasMin {
				g.p("%s = fmt.Errorf(\"%%w: %s.%s cannot go below %d\", dynago.ErrLimit)", v.MinErrName, c.Name, v.Name, v.Min)
			}
		}
	}
	g.p(")")
	g.p("")
}

// errFormat renders the format string of an error wrapping a sentinel with text, which may hold
// schema values: a "%" in them must not be read as a verb.
func errFormat(text string) string {
	return strconv.Quote("%w: " + strings.ReplaceAll(text, "%", "%%"))
}

// views declares result types for indexes that do not return whole entities, and copy items.
func (g *gen) views(e *schema.Entity) {
	lo := lowerFirst(e.GoName)
	for _, ix := range e.Indexes {
		view := e.GoName + ix.GoName
		if !ix.ReturnsEntity() {
			g.p("// %s is %s %s as seen through the %s index: key fields plus the projected fields.", view, article(e.GoName), e.GoName, ix.Name)
			g.p("type %s struct {", view)
			for _, f := range ix.ProjectedFields() {
				g.p("%s %s `dynamo:\"%s\"`", f.GoName, goType(e, f), tag(f, !f.Key))
			}
			g.p("}")
			g.p("")
		}
		if ix.Strategy == schema.StrategyCopy {
			inner := view
			if ix.ReturnsEntity() {
				inner = e.GoName
			}
			g.p("type %s%sCopy struct {", lo, ix.GoName)
			g.p("%s", inner)
			g.p("PK string `dynamo:\"PK\"`")
			g.p("SK string `dynamo:\"SK\"`")
			g.p("T string `dynamo:\"_t\"`")
			g.p("V int `dynamo:\"_v\"`")
			g.p("}")
			g.p("")
		}
	}
}

func (g *gen) counters(e *schema.Entity) {
	for _, c := range e.Counters {
		doc := c.Doc
		if doc == "" {
			doc = fmt.Sprintf("is an atomic counter maintained by every %s write.", e.Name)
		}
		comment(&g.buf, c.GoName+" "+lowerDocStart(doc))
		g.p("type %s struct {", c.GoName)
		for _, v := range c.Values {
			comment(&g.buf, fmt.Sprintf("%s %s.", v.GoName, counterValueText(v)))
			g.p("%s int64 `dynamo:\"%s\"`", v.GoName, v.Attr)
		}
		g.p("}")
		g.p("")
		g.p("// %sKey identifies %s %s counter.", c.GoName, article(c.GoName), c.GoName)
		g.p("type %sKey struct {", c.GoName)
		for _, f := range c.KeyFields() {
			g.p("%s %s", f.GoName, goType(e, f))
		}
		g.p("}")
		g.p("")
	}
}

// limits declares the caller-facing limit structs for writes that can grow limited counters.
func (g *gen) limits(e *schema.Entity) {
	var all []*schema.CounterValue
	for _, c := range e.Counters {
		for _, v := range c.Values {
			if v.LimitArg {
				all = append(all, v)
			}
		}
	}
	if len(all) == 0 {
		return
	}
	lo := lowerFirst(e.GoName)
	g.p("type %sLimits struct {", lo)
	for _, v := range all {
		g.p("%s%s dynago.Limit", v.Counter.GoName, v.GoName)
	}
	g.p("}")
	g.p("")
	for _, w := range e.Writes {
		if len(w.Limits) == 0 {
			continue
		}
		g.p("// %s%sLimits caps the counters %s.%s can grow. Give every field, as dynago.Max(n) or", e.GoName, w.GoName, e.Name, w.Name)
		g.p("// dynago.Unlimited(): a missing limit fails the write with dynago.ErrLimitRequired.")
		g.p("type %s%sLimits struct {", e.GoName, w.GoName)
		for _, v := range w.Limits {
			g.p("%s%s dynago.Limit", v.Counter.GoName, v.GoName)
		}
		g.p("}")
		g.p("")
	}
}

// derived emits the function computing every derived item of an entity state.
func (g *gen) derived(e *schema.Entity) {
	lo := lowerFirst(e.GoName)
	limitsParam := ""
	if hasLimitArgs(e) {
		limitsParam = fmt.Sprintf(", lim %sLimits", lo)
	}
	g.p("// %sDerived returns the counter contributions, claims and copies that exist because of e.", lo)
	g.p("// v is the schema version e was written at: items written before a derived item was")
	g.p("// introduced do not contribute to it.")
	g.p("func %sDerived(e *%s, owner dynago.Key, v int%s) []dynago.Derived {", lo, e.GoName, limitsParam)
	sharded := false
	for _, c := range e.Counters {
		sharded = sharded || c.Shards > 1
	}
	if !sharded {
		g.p("_ = owner // only sharded counters use it")
	}
	g.p("var d []dynago.Derived")
	for _, c := range e.Counters {
		conds := []string{}
		if c.Since > 1 {
			conds = append(conds, fmt.Sprintf("v >= %d", c.Since))
		}
		if pc := presence(c.KeyFields(), "e"); pc != "" {
			conds = append(conds, pc)
		}
		g.p("// counter %s", c.Name)
		g.p("if %s {", orTrue(conds))
		pk := tmplExpr(e, c.PK, "e")
		if c.Shards > 1 {
			pk = fmt.Sprintf("dynago.ShardPK(%s, owner, %d)", pk, c.Shards)
		}
		g.p("k := dynago.Key{PK: %s, SK: %s}", pk, tmplExpr(e, c.SK, "e"))
		for _, v := range c.Values {
			amount := "1"
			if v.Sum != nil {
				amount = "e." + v.Sum.GoName
			}
			extra := ""
			switch {
			case v.LimitArg:
				extra = fmt.Sprintf(", Limit: lim.%s%s, LimitErr: %s, LimitRequired: true", c.GoName, v.GoName, v.ErrName)
			case v.Limit > 0:
				extra = fmt.Sprintf(", Limit: dynago.Max(%d), LimitErr: %s", v.Limit, v.ErrName)
			}
			if v.HasMin {
				extra += fmt.Sprintf(", Min: dynago.Max(%d), MinErr: %s", v.Min, v.MinErrName)
			}
			stmt := fmt.Sprintf("d = append(d, dynago.Derived{Kind: dynago.KindCounter, Key: k, Type: %q, Attr: %q, Amount: %s%s})",
				c.Name, v.Attr, amount, extra)
			var vconds []string
			if v.Since > c.Since {
				vconds = append(vconds, fmt.Sprintf("v >= %d", v.Since))
			}
			if len(v.Where) > 0 {
				vconds = append(vconds, whereExpr(e, v.Where, "e"))
			}
			if len(vconds) > 0 {
				g.p("if %s {", strings.Join(vconds, " && "))
				g.p("%s", stmt)
				g.p("}")
			} else {
				g.p("%s", stmt)
			}
		}
		g.p("}")
	}
	for _, u := range e.Uniques {
		conds := []string{}
		if u.Since > 1 {
			conds = append(conds, fmt.Sprintf("v >= %d", u.Since))
		}
		if pc := presence(u.Fields, "e"); pc != "" {
			conds = append(conds, pc)
		}
		g.p("// unique %s", u.Name)
		g.p("if %s {", orTrue(conds))
		if u.Set == nil {
			g.p("d = append(d, dynago.Derived{Kind: dynago.KindClaim, Key: dynago.Key{PK: %s, SK: %s}, Type: %q, TakenErr: %s})",
				tmplExpr(e, u.PK, "e"), tmplExpr(e, u.SK, "e"), e.Name+"."+u.Name, u.ErrName)
		} else {
			// One claim per element. Elements that render the same key (differing only in case
			// under |lower) share one claim.
			vals := uniqueVals(u, "e", "elem")
			g.p("for _, elem := range e.%s {", u.Set.GoName)
			g.p("if elem != \"\" {")
			g.p("d = append(d, dynago.Derived{Kind: dynago.KindClaim, Key: dynago.Key{PK: %s, SK: %s}, Type: %q, TakenErr: %s})",
				tmplExprVals(e, u.PK, vals), tmplExprVals(e, u.SK, vals), e.Name+"."+u.Name, u.ErrName)
			g.p("}")
			g.p("}")
		}
		g.p("}")
	}
	for _, ix := range e.Indexes {
		if ix.Strategy != schema.StrategyCopy {
			continue
		}
		conds := []string{}
		if ix.Since > 1 {
			conds = append(conds, fmt.Sprintf("v >= %d", ix.Since))
		}
		if pc := presenceAndWhere(e, templateFields(ix.PK, ix.SK, true), ix.Where, "e"); pc != "true" {
			conds = append(conds, pc)
		}
		g.p("// copy index %s", ix.Name)
		g.p("if %s {", orTrue(conds))
		g.p("k := dynago.Key{PK: %s, SK: %s}", tmplExpr(e, ix.PK, "e"), tmplExpr(e, ix.SK, "e"))
		var inner string
		if ix.ReturnsEntity() {
			inner = fmt.Sprintf("%s: *e", e.GoName)
		} else {
			var fs []string
			for _, f := range ix.ProjectedFields() {
				fs = append(fs, fmt.Sprintf("%s: e.%s", f.GoName, f.GoName))
			}
			inner = fmt.Sprintf("%s%s: %s%s{%s}", e.GoName, ix.GoName, e.GoName, ix.GoName, strings.Join(fs, ", "))
		}
		g.p("d = append(d, dynago.Derived{Kind: dynago.KindCopy, Key: k, Type: %q, Item: &%s%sCopy{%s, PK: k.PK, SK: k.SK, T: %q, V: %sVersion}})",
			e.Name+"."+ix.Name, lo, ix.GoName, inner, e.Name+"."+ix.Name, lo)
		g.p("}")
	}
	g.p("return d")
	g.p("}")
	g.p("")
}

