func (g *gen) access(a *schema.Access) {
	e := a.Entity
	switch a.Kind {
	case schema.AccessGet:
		g.docComment(a.GoName, a.Doc, fmt.Sprintf("reads %s %s by primary key with one %s GetItem.", article(e.Name), e.Name, consistency(a.Consistent)))
		g.p("func (s *%sStore) %s(ctx context.Context, k %sKey) (*%s, error) {", e.GoName, a.GoName, e.GoName, e.GoName)
		g.p("key, err := k.dynamoKey()")
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("it, err := s.load(ctx, key, %t)", a.Consistent)
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return &it.%s, nil", e.GoName)
		g.p("}")
		g.p("")
	case schema.AccessGetUnique:
		g.getUnique(a)
	case schema.AccessQuery:
		g.query(a)
	case schema.AccessCounter:
		g.counterRead(a)
	}
}

func (g *gen) getUnique(a *schema.Access) {
	e, u := a.Entity, a.Unique
	var params []string
	vals := map[string]string{}
	for _, f := range u.Fields {
		name := paramName(f)
		typ := goType(e, f)
		if f == u.Set {
			name, typ = paramName(f)+"Elem", "string" // one element of the set
		}
		params = append(params, fmt.Sprintf("%s %s", name, typ))
		vals[f.Name] = name
	}
	what := "the unique " + fieldList(u.Fields)
	if u.Set != nil {
		what = "the given element of " + u.Set.Name
		if len(u.Fields) > 1 {
			what += " (with " + fieldList(slices.DeleteFunc(slices.Clone(u.Fields), func(f *schema.Field) bool { return f == u.Set })) + ")"
		}
	}
	g.docComment(a.GoName, a.Doc, fmt.Sprintf("finds the %s holding %s: a consistent read of the claim, then of the item.", e.Name, what))
	g.p("func (s *%sStore) %s(ctx context.Context, %s) (*%s, error) {", e.GoName, a.GoName, strings.Join(params, ", "), e.GoName)
	for _, f := range u.Fields {
		pc := present(f, vals[f.Name])
		if f == u.Set {
			pc = vals[f.Name] + ` != ""`
		}
		if pc != "" {
			g.p("if %s {", negate(pc))
			g.p("return nil, fmt.Errorf(\"%%w: %s needs %s\", dynago.ErrInvalidKey)", a.Name, f.Name)
			g.p("}")
		}
	}
	for _, f := range u.Fields {
		if f == u.Set {
			g.keyPartCheck(f, vals[f.Name], "return nil, err")
		} else {
			g.keyPartChecks([]*schema.Field{f}, func(f *schema.Field) string { return vals[f.Name] }, "return nil, err")
		}
	}
	g.p("claimKey := dynago.Key{PK: %s, SK: %s}", tmplExprVals(e, u.PK, vals), tmplExprVals(e, u.SK, vals))
	g.p("var claim dynago.Claim")
	g.p("found, err := dynago.GetOne(ctx, s.t, claimKey, true, &claim)")
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("if !found {")
	g.p("return nil, Err%sNotFound", e.GoName)
	g.p("}")
	g.p("it, err := s.load(ctx, dynago.Key{PK: claim.OwnerPK, SK: claim.OwnerSK}, true)")
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("// The claim is only trusted while the item still holds the value it was taken for.")
	if u.Set == nil {
		g.p("if (dynago.Key{PK: %s, SK: %s}) != claimKey {", tmplExpr(e, u.PK, "it"), tmplExpr(e, u.SK, "it"))
		g.p("return nil, Err%sNotFound", e.GoName)
		g.p("}")
	} else {
		vals := uniqueVals(u, "it", "elem")
		g.p("held := false")
		g.p("for _, elem := range it.%s {", u.Set.GoName)
		g.p("held = held || (dynago.Key{PK: %s, SK: %s}) == claimKey", tmplExprVals(e, u.PK, vals), tmplExprVals(e, u.SK, vals))
		g.p("}")
		g.p("if !held {")
		g.p("return nil, Err%sNotFound", e.GoName)
		g.p("}")
	}
	g.p("return &it.%s, nil", e.GoName)
	g.p("}")
	g.p("")
}

func (g *gen) query(a *schema.Access) {
	e := a.Entity
	qt := e.GoName + a.GoName + "Query"
	pk := a.QueryPK()
	sk, hasSK := a.QuerySK()
	result := e.GoName
	if a.Index != nil && !a.Index.ReturnsEntity() {
		result = e.GoName + a.Index.GoName
	}
	if a.Project != nil {
		result = e.GoName + a.GoName + "Item"
		g.p("// %s is what %s.%s returns: the key fields plus %s.", result, e.Name, a.Name, fieldList(a.Project))
		g.p("type %s struct {", result)
		for _, f := range a.ProjectedFields() {
			g.p("%s %s `dynamo:\"%s\"`", f.GoName, goType(e, f), tag(f, !f.Key))
		}
		g.p("}")
		g.p("")
	}
	where := "the table"
	if a.Index != nil {
		where = fmt.Sprintf("the %s index", a.Index.Name)
		if a.Index.Strategy == schema.StrategyCopy {
			where = fmt.Sprintf("the %s copy items", a.Index.Name)
		}
	}
	g.p("// %s selects the partition for %s.%s.", qt, e.Name, a.Name)
	g.p("type %s struct {", qt)
	for _, f := range pk.Fields {
		g.p("%s %s", f.GoName, goType(e, f))
	}
	if a.Range != nil {
		g.p("// From and To bound %s inclusively; nil leaves that end open.", a.Range.Name)
		g.p("From, To *%s", goType(e, a.Range))
	}
	g.p("}")
	g.p("")
	order := "ascending"
	if a.Desc {
		order = "descending"
	}
	g.docComment(a.GoName, a.Doc, fmt.Sprintf("returns one page of %s items from %s, %s by %q, with exactly one %s Query (default %d, max %d items). It returns the cursor for the next page, or \"\" at the end.",
		e.Name, where, order, sk.Raw, consistency(a.Consistent), a.Page, a.MaxPage))
	g.p("func (s *%sStore) %s(ctx context.Context, q %s, page dynago.Page) ([]%s, string, error) {", e.GoName, a.GoName, qt, result)
	g.presenceGuard(pk.Fields, "q", fmt.Sprintf("return nil, \"\", fmt.Errorf(\"%%w: %s needs %s\", dynago.ErrInvalidKey)", a.Name, fieldList(pk.Fields)))
	g.keyPartChecks(pk.Fields, func(f *schema.Field) string { return "q." + f.GoName }, "return nil, \"\", err")
	g.p("pk := %s", tmplExpr(e, pk, "q"))
	spec := []string{
		// The scope ties a cursor to this query, its partition and the schema version.
		fmt.Sprintf("Scope: %q + pk", fmt.Sprintf("%s.%s@v%d\x00", e.Name, a.Name, e.Version)),
		"PK: pk",
		fmt.Sprintf("PageSize: %d", a.Page),
		fmt.Sprintf("MaxPage: %d", a.MaxPage),
	}
	prefix := ""
	if hasSK {
		prefix = sk.LiteralPrefix()
	}
	if a.Index != nil && a.Index.Strategy == schema.StrategyGSI {
		spec = append(spec, fmt.Sprintf("Index: %q", a.Index.Name), fmt.Sprintf("PKAttr: %q", a.Index.PKAttr))
		if hasSK {
			spec = append(spec, fmt.Sprintf("SKAttr: %q", a.Index.SKAttr))
		}
	} else {
		spec = append(spec, `PKAttr: "PK"`, `SKAttr: "SK"`)
	}
	if prefix != "" {
		spec = append(spec, fmt.Sprintf("Prefix: %q", prefix))
	}
	if a.Desc {
		spec = append(spec, "Desc: true")
	}
	if a.Consistent {
		spec = append(spec, "Consistent: true")
	}
	if e.TTL != nil && (a.Index == nil || a.Index.Strategy == schema.StrategyGSI) {
		spec = append(spec, fmt.Sprintf("TTLAttr: %q", g.m.Table.TTLAttr))
	}
	if a.Project != nil {
		var attrs []string
		for _, f := range a.ProjectedFields() {
			attrs = append(attrs, f.Attr)
		}
		spec = append(spec, "Project: "+stringSlice(attrs))
	}
	g.p("spec := dynago.QuerySpec{%s}", strings.Join(spec, ", "))
	if a.Range != nil {
		bound := func(recv string) string {
			x := transformExpr(rangeTransform(sk, a.Range), fmtExpr(a.Range, recv))
			if prefix != "" {
				x = strconv.Quote(prefix) + " + " + x
			}
			return x
		}
		g.p("if q.From != nil {")
		g.p("from := %s", bound("*q.From"))
		g.p("spec.From = &from")
		g.p("}")
		g.p("if q.To != nil {")
		g.p("to := %s", bound("*q.To"))
		g.p("spec.To = &to")
		g.p("}")
	}
	if result == e.GoName {
		g.p("var raws []dynamo.Item")
		g.p("next, err := dynago.Query(ctx, s.t, spec, page, &raws)")
		g.p("if err != nil {")
		g.p("return nil, \"\", err")
		g.p("}")
		g.p("out, err := %sDecodeAll(raws)", lowerFirst(e.GoName))
		if a.Index != nil && a.Index.Strategy == schema.StrategyCopy {
			g.p("// Copies don't store the item's revision, so these entities have no version:")
			g.p("// Version() is \"\", and dynago.From refuses them. Get the item for a version.")
			g.p("for i := range out {")
			g.p("out[i].loaded = nil")
			g.p("}")
		}
		g.p("return out, next, err")
		g.p("}")
		g.p("")
		return
	}
	g.p("var out []%s", result)
	g.p("next, err := dynago.Query(ctx, s.t, spec, page, &out)")
	g.p("if err != nil {")
	g.p("return nil, \"\", err")
	g.p("}")
	g.p("return out, next, nil")
	g.p("}")
	g.p("")
}

func (g *gen) counterRead(a *schema.Access) {
	c := a.Counter
	e := c.Entity // the counter's fields belong to the entity it counts
	g.docComment(a.GoName, a.Doc, fmt.Sprintf("reads the %s counter (%s). A counter nothing has touched reads as zero.",
		c.Name, readCost(c, a.Consistent)))
	g.p("func (s *%sStore) %s(ctx context.Context, k %sKey) (%s, error) {", a.Entity.GoName, a.GoName, c.GoName, c.GoName)
	g.presenceGuard(c.KeyFields(), "k", fmt.Sprintf("return %s{}, fmt.Errorf(\"%%w: %s needs %s\", dynago.ErrInvalidKey)", c.GoName, c.Name, fieldList(c.KeyFields())))
	g.keyPartChecks(c.KeyFields(), func(f *schema.Field) string { return "k." + f.GoName }, fmt.Sprintf("return %s{}, err", c.GoName))
	if c.Shards <= 1 {
		g.p("var out %s", c.GoName)
		g.p("_, err := dynago.GetOne(ctx, s.t, dynago.Key{PK: %s, SK: %s}, %t, &out)", tmplExpr(e, c.PK, "k"), tmplExpr(e, c.SK, "k"), a.Consistent)
		g.p("return out, err")
		g.p("}")
		g.p("")
		return
	}
	g.p("sk := %s", tmplExpr(e, c.SK, "k"))
	g.p("var keys []dynago.Key")
	g.p("for _, pk := range dynago.ShardPKs(%s, %d) {", tmplExpr(e, c.PK, "k"), c.Shards)
	g.p("keys = append(keys, dynago.Key{PK: pk, SK: sk})")
	g.p("}")
	g.p("var parts []%s", c.GoName)
	g.p("if err := dynago.GetMany(ctx, s.t, keys, %t, &parts); err != nil {", a.Consistent)
	g.p("return %s{}, err", c.GoName)
	g.p("}")
	g.p("var out %s", c.GoName)
	g.p("for _, p := range parts {")
	for _, v := range c.Values {
		g.p("out.%s += p.%s", v.GoName, v.GoName)
	}
	g.p("}")
	g.p("return out, nil")
	g.p("}")
	g.p("")
}

