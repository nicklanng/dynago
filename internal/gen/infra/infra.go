// Package infra renders the table definition as Terraform JSON and as a CreateTable request.
package infra

import (
	"encoding/json"
	"regexp"
	"strings"

	"github.com/nicklanng/dynago"
	"github.com/nicklanng/dynago/internal/schema"
)

// Spec returns the runtime table spec for the model: the same value the generated Go code
// embeds as TableSpec.
func Spec(m *schema.Model) dynago.TableSpec {
	spec := dynago.TableSpec{}
	for _, e := range m.Entities {
		if e.TTL != nil {
			spec.TTLAttr = m.Table.TTLAttr
		}
	}
	for _, g := range m.GSIs {
		gs := dynago.GSISpec{Name: g.Name, PKAttr: g.PKAttr, Projection: "ALL"}
		if g.HasSK {
			gs.SKAttr = g.SKAttr
		}
		if g.Projection == schema.ProjectInclude {
			gs.Projection = "INCLUDE"
			gs.NonKeyAttrs = g.NonKeyAttrs
		}
		spec.GSIs = append(spec.GSIs, gs)
	}
	return spec
}

var nonIdent = regexp.MustCompile(`[^a-z0-9_]+`)

// resourceName turns a table name into a Terraform identifier, which must start with a letter or
// underscore.
func resourceName(table string) string {
	name := strings.Trim(nonIdent.ReplaceAllString(strings.ToLower(table), "_"), "_")
	if name == "" || (name[0] >= '0' && name[0] <= '9') {
		name = "table_" + name
	}
	return name
}

// Terraform renders an aws_dynamodb_table resource in Terraform's JSON syntax. The table name is
// a variable (defaulting to the schema's table name) so environments can suffix it.
func Terraform(m *schema.Model, source string) ([]byte, error) {
	spec := Spec(m)
	res := resourceName(m.Table.Name)
	varName := res + "_table_name"

	attrs := []map[string]string{{"name": "PK", "type": "S"}, {"name": "SK", "type": "S"}}
	var gsis []map[string]any
	for _, g := range spec.GSIs {
		attrs = append(attrs, map[string]string{"name": g.PKAttr, "type": "S"})
		gsi := map[string]any{"name": g.Name, "hash_key": g.PKAttr, "projection_type": g.Projection}
		if g.SKAttr != "" {
			attrs = append(attrs, map[string]string{"name": g.SKAttr, "type": "S"})
			gsi["range_key"] = g.SKAttr
		}
		if g.Projection == "INCLUDE" {
			gsi["non_key_attributes"] = g.NonKeyAttrs
		}
		gsis = append(gsis, gsi)
	}
	table := map[string]any{
		"name":                        "${var." + varName + "}",
		"billing_mode":                "PAY_PER_REQUEST",
		"hash_key":                    "PK",
		"range_key":                   "SK",
		"attribute":                   attrs,
		"deletion_protection_enabled": true,
		"point_in_time_recovery":      map[string]bool{"enabled": true},
	}
	if len(gsis) > 0 {
		table["global_secondary_index"] = gsis
	}
	if spec.TTLAttr != "" {
		table["ttl"] = map[string]any{"attribute_name": spec.TTLAttr, "enabled": true}
	}
	doc := map[string]any{
		"//": "Generated by dynago from " + source + ". Do not edit.",
		"variable": map[string]any{
			varName: map[string]any{"type": "string", "default": m.Table.Name, "description": "Name of the " + m.Table.Name + " DynamoDB table."},
		},
		"resource": map[string]any{
			"aws_dynamodb_table": map[string]any{res: table},
		},
		"output": map[string]any{
			res + "_table_arn": map[string]any{"value": "${aws_dynamodb_table." + res + ".arn}"},
		},
	}
	return marshal(doc)
}

// CreateTableJSON renders the CreateTable request for `aws dynamodb create-table --cli-input-json`.
func CreateTableJSON(m *schema.Model) ([]byte, error) {
	spec := Spec(m)
	in := spec.CreateTableInput(m.Table.Name)
	attrs := []map[string]string{}
	for _, a := range in.AttributeDefinitions {
		attrs = append(attrs, map[string]string{"AttributeName": *a.AttributeName, "AttributeType": string(a.AttributeType)})
	}
	doc := map[string]any{
		"TableName":            *in.TableName,
		"BillingMode":          string(in.BillingMode),
		"AttributeDefinitions": attrs,
		"KeySchema": []map[string]string{
			{"AttributeName": "PK", "KeyType": "HASH"},
			{"AttributeName": "SK", "KeyType": "RANGE"},
		},
	}
	var gsis []map[string]any
	for _, g := range in.GlobalSecondaryIndexes {
		ks := []map[string]string{}
		for _, k := range g.KeySchema {
			ks = append(ks, map[string]string{"AttributeName": *k.AttributeName, "KeyType": string(k.KeyType)})
		}
		proj := map[string]any{"ProjectionType": string(g.Projection.ProjectionType)}
		if len(g.Projection.NonKeyAttributes) > 0 {
			proj["NonKeyAttributes"] = g.Projection.NonKeyAttributes
		}
		gsis = append(gsis, map[string]any{"IndexName": *g.IndexName, "KeySchema": ks, "Projection": proj})
	}
	if len(gsis) > 0 {
		doc["GlobalSecondaryIndexes"] = gsis
	}
	return marshal(doc)
}

func marshal(v any) ([]byte, error) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
